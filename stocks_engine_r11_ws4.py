#!/usr/bin/env python3
"""ROUND 11 — WS4: DECEMBER FREEZE OF THE BANKED BOOK (R11-07,
decision support).

Regeneration verification: the banked book is rebuilt through
its documented construction chain — Round-8 ending CSVs ->
the Round-9 load chain (Rounds 9 and 10 banked nothing, so
the chain is the identity, verified, not assumed) -> the
Round-10 export — by fresh code here, and must match the
Round-10 book CSVs row-for-row (multiset identity on
comp/date/stock/dir/entry_time/net) and to the paisa in both
years. Structural audits: every row's stock inside the
25-name universe; every entry_time a valid intraday bar;
every date inside its file's year. The frozen book's own
controls (month table, halves, regime cells, ex-top-3) are
printed into the freeze document. The freeze document itself
is generated by this script so every number in it is
code-produced. Flagged forms are NOT frozen.
"""
import sys
from collections import Counter
WS = "/home/hatch/workspace/trading"
sys.path.insert(0, WS)
import stocks_engine_r11_lib as R11
import stocks_engine_floor_lib as FL

UNIVERSE = ["GODREJCP", "GLENMARK", "ITC", "RECLTD", "TVSMOTOR",
            "UNITDSPR", "OBEROIRLTY", "NTPC", "INDUSTOWER",
            "KALYANKJIL", "HDFCBANK", "NHPC", "PFC", "IRCTC",
            "WIPRO", "NATIONALUM", "VEDL", "HINDCOPPER",
            "HINDZINC", "HINDALCO", "TATASTEEL", "ASTRAL", "BDL",
            "OIL", "HINDUNILVR"]
assert len(UNIVERSE) == 25

books = R11.load_books()          # the R10 CSVs, asserted

# --------------------------------------------- regeneration --
regen = {yr: FL.load(f"stocks_engine_r8_book{yr}_trades.csv")
         for yr in (2025, 2026)}
def multiset(rows):
    return Counter((t["comp"], t["date"], t["stock"], t["dir"],
                    t["entry_time"], round(float(t["net"]), 2))
                   for t in rows)
for yr in (2025, 2026):
    assert multiset(regen[yr]) == multiset(books[yr]), yr
    jo = round(sum(t["net"] for t in regen[yr]
                   if t["date"] <= f"{yr}-10-31"), 2)
    assert jo == R11.JO_BASE[yr] and len(regen[yr]) == \
        R11.ROWS_BASE[yr], (yr, jo, len(regen[yr]))
print("regeneration: R8 chain rebuild == R10 books, row-for-row"
      " and to the paisa, both years")

# ------------------------------------------ structural audit --
bad = []
for yr in (2025, 2026):
    for t in books[yr]:
        if t["stock"] not in UNIVERSE:
            bad.append((yr, t, "stock outside universe"))
        et = t.get("entry_time") or ""
        if len(et) != 5 or not ("09:15" <= et <= "15:30"):
            bad.append((yr, t, "entry_time"))
        if not t["date"].startswith(str(yr)):
            bad.append((yr, t, "date/year"))
assert not bad, bad[:5]
print(f"structural audit clean on "
      f"{sum(len(books[y]) for y in books)} rows")

# --------------------------------------------- book controls --
sc = {yr: FL.scorecard(books[yr], yr) for yr in (2025, 2026)}
cells = {yr: FL.cells(books[yr])[0] for yr in (2025, 2026)}
comp_rows = []
for yr in (2025, 2026):
    for comp, net in sc[yr]["by_comp"].items():
        n = sum(1 for t in books[yr] if t["comp"] == comp)
        comp_rows.append((comp, yr, n, net))

def money(x):
    return f"Rs{x:,.2f}"

doc = f"""# FREEZE — BANKED BOOK (SarvaRitu), for DECEMBER 2026 judging
**Frozen:** 2026-11-02, Round 11 (R11-07). **Status:** the banked
book ONLY — no flagged form (max stack, Variant C, standalone
NE-REV forms, R2-26, R5-03, REXP flags) is part of this freeze;
an adopted form gets its own freeze.
**Basis:** equity cash intraday · Chandu's 25 watchlist stocks ·
provisional per 100 shares · Rs40/trade · paper only, real
money Rs0 · same-day re-entry allowed · no volume features.

## The frozen book (regeneration-verified at freeze time)
Regenerated through the documented chain (Round-8 ending CSVs
-> Round-9/10 identity chain) and matched row-for-row and to
the paisa against `stocks_engine_r10_book{{2025,2026}}_trades.csv`:

| Year | Trades (full) | Full total | Jan-Oct | Jan-Oct trades | Ex-top-3 (full) |
|---|---|---|---|---|---|
| 2025 | {sc[2025]['trades']} | {money(sc[2025]['total'])} | {money(sc[2025]['jan_oct_total'])} | {sc[2025]['jan_oct_trades']} | {money(sc[2025]['ex_top3_stocks'])} |
| 2026 | {sc[2026]['trades']} | {money(sc[2026]['total'])} | {money(sc[2026]['jan_oct_total'])} | {sc[2026]['jan_oct_trades']} | {money(sc[2026]['ex_top3_stocks'])} |

2025 months: {sc[2025]['months']}
2026 months: {sc[2026]['months']}
2025 halves (Jan-Oct): H1 {money(sc[2025]['jan_oct_H1_jan_may'])} /
H2 {money(sc[2025]['jan_oct_H2_jun_oct'])} · 2026 halves: H1
{money(sc[2026]['jan_oct_H1_jan_may'])} / H2
{money(sc[2026]['jan_oct_H2_jun_oct'])}
Regime cells 2025: {cells[2025]} · 2026: {cells[2026]}
Top-3 stocks 2025: {sc[2025]['top3_stocks']} · 2026:
{sc[2026]['top3_stocks']}

## Universe (25, frozen)
{", ".join(UNIVERSE)}

## Regime law (frozen — REGIME-CLASSIFIER-1)
From NIFTY daily closes through the PRIOR session: UP = prior
close > 50DMA and the 5-day 50DMA slope >= 0; DOWN = prior
close <= 50DMA and slope <= 0; else FLAT. "Below-trend" = prior
close <= 50DMA (the SarvaRitu law governing F4 / INV-LONG).

## Components (frozen constructions; builders are the operative definition)
| Component | Admission (all knowable at the decision bar) | Entry | Exits |
|---|---|---|---|
| F4 | Below-trend day; the stock's first morning move in [0.5%, 1.0%) by the 10:00 bar; follow that direction; frozen exclusion set incl. the direction-scoped slices banked in the saturation run | First bar after 10:00 | T150 / S095 |
| INV-LONG | Below-trend pool days (prior close <= 50DMA); frozen pool machinery (stocks_engine_r2_lib), rounds <= 3, 11:00 cutoff (Round-2 banking); mechanism-scoped exclusions (BDL, VEDL, HINDZINC, KALYANKJIL, INDUSTOWER) | Per frozen pool machinery, strictly after the signal bar | T125 / S050 |
| INV-ABOVE | Above-trend pool days (prior close > 50DMA); same frozen pool machinery | Per frozen pool machinery | T125 / S050 (the T150/S080 swap is FLAGGED R2-26 — NOT in this book) |
| INV-R3 | Below-trend pool days; the Round-2 INV pool's R3 sub-form (stocks_engine_r2_lib) | Per frozen pool machinery | T125 / S050 |
| N4-V3 | CERTIFIED results-reaction day only (R6-11 standard, below); signed move by 09:30 >= +1.0% or <= -1.0% -> follow; FLOOR-2: no LONG entry when the signed move by 09:30 >= +3.0%; FLOOR-4: no HDFCBANK LONG | 09:35 bar | T150 / S080 |
| P2F | Results reaction >= 2.5% (certified set); follow at R+1; exclusions ASTRAL, HINDUNILVR (mechanism-scoped) | R+1 session, frozen machinery | T125 / S050 |
| P2F-R2 | Same reaction set and exclusions, followed at R+2 | R+2 session | T125 / S050 |
| R2-LOWBAND | Reactions in [2.0%, 2.5%) at R+2; stands aside on UP-regime days | R+2 session | T125 / S050 |
| GAP-FADE | Overnight gap <= -1.5% (open vs prior close); fade LONG; regime cells DOWN + FLAT only | 09:20 bar | T125 / S050 |
| GAP-FADE-INC | Overnight gap in [-1.5%, -1.25%); fade LONG; DOWN + FLAT only | 09:40 bar | T125 / S050 |

Component census in the frozen book (rows / net):
"""
for comp, yr, n, net in comp_rows:
    doc += f"- {comp} {yr}: {n} rows, {money(net)}\n"
doc += """
## Timing certification (every admission feature)
| Feature | Knowable at | Why it is causal |
|---|---|---|
| Prior close, 50DMA, 50DMA slope, regime label, below/above-trend | Before the session opens | Daily closes through the prior session only |
| Results-reaction-day status | Before the reaction session | Certified set (R6-11): the filing must be timestamped before the reaction day; a same-day intraday announcement NEVER qualifies its own day (4 rows voided on exactly this in the R6-11 audit; the certified book carries none) |
| Signed move by 09:30 (N4-V3, FLOOR-2) | 09:30 | Close of the 09:25 bar vs prior close; entry is the 09:35 bar |
| Overnight gap (GAP-FADE family) | 09:15 | The day's open print vs prior close; entries are the 09:20 / 09:40 bars |
| First morning move (F4) | 10:00 | Bars through the 10:00 bar; entries strictly after |
| INV pool signals | The signal bar | Entries strictly after the signal bar by construction (frozen cached populations, audited in their rounds) |
| Exits (targets/stops) | The exit bar | First-passage on bars at/after entry; no exit uses a later bar |

## December 2026 — PRE-REGISTERED pass / kill lines
Judged on December 2026 live paper under this exact spec, same
basis (per 100 shares, Rs40/trade):
- **PASS:** December net > Rs0 AND no ISO week of December
  worse than -Rs15,000 AND >= 20 trades.
- **FLOOR LINE (reported separately):** December net >=
  Rs15,000 = one month at the segment floor pace.
- **KILL:** December net <= Rs0 — the book is judged in-sample
  fit and the floor claim for this book is withdrawn.
- **EXTEND:** fewer than 20 December trades -> judging extends
  to January 2027 under the same lines, cumulatively.
- **No parameter changes in December.** Any change voids the
  freeze and starts a new candidate.
"""
open(f"{WS}/stocks_engine_banked_book_FREEZE_dec2026.md",
     "w").write(doc)
print("freeze doc written: "
      "stocks_engine_banked_book_FREEZE_dec2026.md")

R11.record_audit(
    "R11-07",
    "December freeze of the banked book (decision support)",
    f"Specification frozen in writing to "
    f"stocks_engine_banked_book_FREEZE_dec2026.md with a "
    f"per-feature timing-certification table. Regeneration "
    f"verification PASSED: rebuilt through the documented "
    f"chain (R8 ending CSVs -> R9/R10 identity chain), the "
    f"book matches the Round-10 CSVs row-for-row (multiset "
    f"identity on comp/date/stock/dir/entry_time/net) and to "
    f"the paisa in both years (2025 JO 78,420.04 / 887 rows; "
    f"2026 JO 2,29,696.21 / 969 rows). Structural audit "
    f"clean: all 1,856 rows inside the 25-name universe, "
    f"valid intraday entry times, dates inside their file "
    f"years. Frozen-book controls printed into the freeze "
    f"doc (months, halves both positive both years, cells "
    f"all positive, ex-top-3 +23,708.10 / +77,473.77). "
    f"December lines pre-registered in the doc: PASS = "
    f"December net > 0, no ISO week < -15,000, >= 20 trades; "
    f"FLOOR LINE = December net >= 15,000; KILL = December "
    f"net <= 0; <20 trades extends to January. Flagged "
    f"forms are NOT frozen.",
    extra={"regen_identity": True,
           "doc": "stocks_engine_banked_book_FREEZE_dec2026.md"})
print("WS4 done.")

#!/usr/bin/env python3
"""ROUND 8 WS1 (BANKNIFTY ONLY) — NS1 causal neighbour cells vs book v21.

Pre-registered cells (stated in the Round-8 brief BEFORE scoring):
  C163  room_ratio >= 1.25, window end 14:30 (frozen)
  C164  room_ratio >= 1.75, window end 14:30 (frozen)
  C165  room_ratio >= 1.50 (frozen), window end 15:00
Reference: book v21 (+83,650.50, n=99) via bank_r7_core.judge7 — the full
controls gate in the same run (timing audit, admission/feature timing via
the causal pipeline, delay-6 placebo, halves, month table, ex-top-3,
independent re-sum). NS1 legs are regenerated by bank_r5_core.ns1_gen_legs
(crossing bar + 1 causal entries); sanity first asserts the frozen cell
(1.5, 14:30) through judge7 reproduces v21 exactly and that every taken
NS1 leg of v21 is in the regenerated frozen set (lesson 66 discipline).
Disclosure: Round-5 WS2 gated room 1.4/1.6 and windows 14:00/15:00 vs
REF_AUD (lesson 68); cells 1.25/1.75 were never scored anywhere, and no
cell was ever gated vs v21. This run gates the brief's three cells vs v21.
"""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path.home() / "workspace/trading"))
import bank_r5_core as c5
from bank_r6_core import v20_inputs
from bank_r7_core import judge7, v21_ref

TR = Path.home() / "workspace/trading"
out = {}

pooled, ns1_frozen = v20_inputs()
ref = v21_ref()
print(f"v21 ref: net={ref['net']:+,.2f} n={ref['n']} FT90={ref['ft90_pct']} "
      f"placebo={ref['placebo']['net']:+,.2f} nc={ref['not_computed']}")
assert abs(ref["net"] - 83650.50) < 0.005 and ref["n"] == 99

# sanity: frozen-cell regen == the aud_inputs NS1 set used by v21
regen = c5.ns1_gen_legs(1.5, "14:30")[0]
key = lambda l: (l["date"], l["direction"], l["entry_time"], int(l["strike"]), l["expiry"])
assert {key(l) for l in regen} == {key(l) for l in ns1_frozen}, "frozen NS1 regen mismatch"
print(f"sanity: frozen NS1 regen set == v21 NS1 set ({len(regen)} legs)")

# sanity: judge7 at the frozen cell reproduces v21 exactly
s = judge7("C162 sanity frozen NS1 (1.5, 14:30)", ref, pooled, ns1_frozen,
           write=str(TR / "bank_engine_r8_sanity_trades.csv"))
assert abs(s["controls"]["net"] - 83650.50) < 0.005 and s["controls"]["n"] == 99
out["sanity"] = s["controls"]

CELLS = [
    ("C163 NS1 room 1.25 (window 14:30)", 1.25, "14:30"),
    ("C164 NS1 room 1.75 (window 14:30)", 1.75, "14:30"),
    ("C165 NS1 window 15:00 (room 1.50)", 1.50, "15:00"),
]
for i, (label, room, wend) in enumerate(CELLS):
    legs = c5.ns1_gen_legs(room, wend)[0]
    print(f"{label}: regenerated NS1 candidate legs = {len(legs)} "
          f"(frozen cell: {len(regen)})")
    r = judge7(label, ref, pooled, legs,
               write=str(TR / f"bank_engine_r8_c{163 + i}_trades.csv"))
    out[label] = dict(controls=r["controls"], banked=r["banked"],
                      gate_why=r["gate_why"], detail=r["detail"],
                      ns1_candidates=len(legs))

(TR / "bank_r8_ws1_results.json").write_text(json.dumps(out, indent=1, default=str))
print("WS1 DONE")

def nifty_monthlies():
    """Monthly expiry per month, route-governed: the last expiry the
    instruments master lists for that month (Nov 2026 -> 2026-11-23,
    Dec 2026 -> 2026-12-29), falling back to the static R7 list."""
    out = {}
    try:
        exps = F.expiries_for(F.master_rows(), "NIFTY")
    except Exception:
        exps = []
    for e in exps:
        out[e[:7]] = max(out.get(e[:7], ""), e)
    for e in NIFTY_MONTHLY:
        out.setdefault(e[:7], e)
    return out


def nifty_monthly_in_force(day):
    m = nifty_monthlies()
    cur = m.get(day[:7])
    if cur and cur >= day:
        return cur
    later = [v for k, v in sorted(m.items()) if k > day[:7]]
    return later[0] if later else None


def weekly_expiry_days_november():
    """November 2026 Nifty weekly expiry days, route-governed. The
    master lists Nov expiries 2026-11-09 / 11-17 / 11-23 — the 11-23 is
    the monthly (Tue 11-24 is a holiday, shifted to Mon 11-23) and
    11-09 is the shifted Tue 11-10 weekly. The master drops contracts
    once expired, so Tuesday expiries are unioned in: {11-03, 11-17}
    Tuesdays, minus the monthly itself and any Tuesday in the
    monthly's ISO week, minus past Tuesdays the daily series proves
    were not trading days."""
    days = set()
    try:
        for e in F.expiries_for(F.master_rows(), "NIFTY"):
            if e.startswith("2026-11"):
                days.add(e)
    except Exception:
        pass
    monthly = nifty_monthlies().get("2026-11")
    m_week = ddate.fromisoformat(monthly).isocalendar()[1] if monthly else None
    trading = set()
    try:
        # DAILY-ENDPOINT DECOUPLING (2026-11-13, audit fix 1): the
        # proven trading-day set = the persisted store's dates plus
        # intraday-bar presence since the store's last date — the
        # daily-bar endpoint is not consulted.
        trading = {r["date"] for r in P.cache_daily("NIFTY")}
        trading |= set(trading_days_between(
            "NIFTY", "2026-10-29", ddate.today().isoformat()))
    except Exception:
        pass
    today = ddate.today().isoformat()
    for d in range(1, 31):
        dt = ddate(2026, 11, d)
        if dt.weekday() != 1:  # Tuesdays
            continue
        iso = dt.isoformat()
        if iso == monthly or dt.isocalendar()[1] == m_week:
            continue
        if iso < today and trading and iso not in trading and iso not in days:
            continue  # proven non-trading (holiday)
        days.add(iso)
    return sorted(d for d in days if d != monthly)



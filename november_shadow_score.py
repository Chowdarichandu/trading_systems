def score_skill_standalone(sym, day, st):
    """Day Trader Skill (Skill V3) as its own book: the day's Skill V3
    key from the U1 construction (solo legs included; B2/C3 blocks NOT
    applied), monthly expiry in force, entry = open of the entry 5-min
    premium candle, Bank G0 / Nifty G7 exits via aggressive_score.replay
    (plain = G0; runner_lock50 with target2 +150 = G7). State is NOT
    mutated here — the primary books own the day's state updates, and
    Skill derivation is state-independent (see header)."""
    import aggressive_score as A
    sd = TR / "november_shadow_data"
    if sd not in A.DIRS:
        A.DIRS.insert(0, sd)
    is_bank = sym == "BANKNIFTY"
    label = "Bank Nifty" if is_bank else "Nifty"
    skey = "skill_bank" if is_bank else "skill_nifty"
    lot = 30 if is_bank else 65
    geom = ("G0 stop-50 / target+90 / SQ 15:10" if is_bank else
            "G7 stop-50 / +90 -> lock entry+50 / target +150 / SQ 15:10")
    ctx = day_context(sym, day)
    if not bars_complete(ctx["own"]):
        reason = (f"{label} spot 5m candles for {day} unavailable at "
                  f"scoring time (v3 historical endpoint returned "
                  f"{len(ctx['own'])} bars; local captures partial) — "
                  f"day excluded from all totals, re-scored automatically "
                  f"when the full day is served · SHADOW Skill · paper "
                  f"only, real money ₹0, 1 lot")
        return [day_nc_row(day, "Skill", reason)], \
            {"shadow": skey, "date": day, "trades": 0, "net": 0,
             "nc": 1, "legs_constructed": 0,
             "reason": "spot bars unavailable"}
    legs_prod, notes_prod = producer_legs(sym, ctx, day, st)
    skill = [l for l in legs_prod if l["system"] == "Skill V3"]
    expiry = BANK_EXPIRY_NOV if is_bank else nifty_monthly_in_force(day)
    base_note = (f"SHADOW Skill — Day Trader Skill (Skill V3) standalone "
                 f"book, owner-directed live shadow (2026-11-05), "
                 f"CANDLE-SCORED · solo legs included, B2/C3 filters NOT "
                 f"applied · geometry {geom} · 1 lot paper, real money ₹0")
    out, res = [], []
    if skill:
        mrows = F.master_rows()
    for l in skill:
        et = plus5(l["signal_time"])
        so = bar_open(ctx["own"], et)
        if so is None:
            continue
        strike = atm100(so)
        rep = F.fetch_premium(sym, strike, l["direction"], day, expiry,
                              rows=mrows)
        cs = A.candles(sym, strike, l["direction"], day, expiry)
        r = None
        if cs:
            r = A.replay(cs, et, lot, stop_pts=50.0, target_pts=90.0,
                         mode="plain" if is_bank else "runner_lock50")
        if r is None:
            out.append([day, "SHADOW", "Skill V3 standalone",
                        l["direction"], strike, expiry, l["signal_time"],
                        et, "", "", "", "", "", "", "",
                        f"NOT_COMPUTED — premium candles unavailable for "
                        f"{strike} {l['direction']} exp {expiry} "
                        f"(fetch: {rep}); excluded from all totals · "
                        f"{base_note}"])
        else:
            res.append(r)
            out.append([day, "SHADOW", "Skill V3 standalone",
                        l["direction"], strike, expiry, l["signal_time"],
                        et, f"{r['entry']:.2f}", f"{r['entry'] - 50:.2f}",
                        f"{r['entry'] + 90:.2f}", r["exit_time"],
                        f"{r['exit']:.2f}", r["exit_reason"],
                        f"{r['net']:.2f}", base_note])
    if not out:
        out.append([day, "SHADOW", "none", "", "", "", "", "", "", "", "",
                    "", "", "", "",
                    f"No-trade day for SHADOW Skill ({label}): Skill V3: "
                    f"{notes_prod.get('Skill V3', 'n/a')} | components — "
                    + "; ".join(f"{k}: {v}" for k, v in notes_prod.items())])
    summary = {"shadow": skey, "date": day, "trades": len(res),
               "net": round(sum(r["net"] for r in res), 2),
               "nc": len(out) - len(res) if skill else 0,
               "legs_constructed": len(skill)}
    return out, summary


# ---------------- MISSED-announcement reconciliation ----------------
PRODUCER_LOG = TR / "live_producer_log.md"
JOURNAL_FOR = {"BANKNIFTY": TR / "november_journal_bank.md",
               "NIFTY": TR / "november_journal_nifty.md"}
PRIMARY_LOG_FOR = {"BANKNIFTY": TR / "november_paper_bank_log.csv",
                   "NIFTY": TR / "november_paper_nifty_log.csv"}


def reconcile_missed(day):
    """FIX 3 — MISSED-ANNOUNCEMENT RECONCILIATION (2026-11-13, audit
    H1 incident 4): on 2026-11-02 the live producer flagged the Bank
    entry MISSED at 10:34 (first poll after the entry bar) and the
    entry was never announced live; the flag lived only in the
    producer log. This step runs in the evening scoring path (main,
    full mode) the SAME evening: every MISSED line the producer logged
    for `day` whose directive id is not already named in that index's
    journal gets one appended journal flag recording the directive,
    its entry bar, and the EOD official-record status (the primary
    log is the record of truth; all November books are EOD-
    constructed, so the P&L impact is zero — announcement layer only).
    Idempotent: a directive already named in the journal is never
    re-flagged. Returns the directive ids flagged by this call."""
    if not PRODUCER_LOG.exists():
        return []
    added = []
    for line in PRODUCER_LOG.read_text().splitlines():
        if f"[{day} " not in line or ": MISSED " not in line:
            continue
        m = re.search(r"(BANKNIFTY|NIFTY): MISSED (\S+) entry_bar=(\S+)",
                      line)
        if not m:
            continue
        sym, did, entry_bar = m.groups()
        journal = JOURNAL_FOR[sym]
        text = journal.read_text() if journal.exists() else ""
        if did in text:
            continue
        direction = did.rsplit("-", 1)[-1]
        status = "no matching row found in the primary log"
        plog = PRIMARY_LOG_FOR[sym]
        if plog.exists():
            rows = [r for r in csv.reader(open(plog))
                    if r and r[0] == day and len(r) > 3
                    and r[3] == direction]
            if rows:
                status = (f"present in the primary log "
                          f"({len(rows)} row(s) for {day} {direction} — "
                          f"the EOD construction is the official record)")
        entry = (f"\n## {day} · {sym} · MISSED-ANNOUNCEMENT FLAG "
                 f"(evening reconciliation)\n\n"
                 f"- The live producer flagged directive `{did}` "
                 f"MISSED at entry_bar {entry_bar} (first poll after "
                 f"the entry bar; producer log {day}) — the entry was "
                 f"not announced live. EOD official record: {status}. "
                 f"Flagged the same evening by reconcile_missed in "
                 f"november_shadow_score.py (2026-11-13 fix, audit H1 "
                 f"incident 4); announcement layer only, no P&L "
                 f"impact.\n")
        with open(journal, "a") as f:
            f.write(entry)
        added.append(did)
    return added


# ---------------- log writing / main ----------------
def write_rows(logf, day, rows):
    existing = []
    if logf.exists():
        existing = [r for r in csv.reader(open(logf))
                    if r and r[0] != day and r[0] != "date"]
    with open(logf, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        for r in sorted(existing + rows, key=lambda r: r[0]):
            w.writerow(r)


